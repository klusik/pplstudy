try {
    if (($_SERVER['REQUEST_METHOD'] ?? 'GET') === 'POST') {
        if (!hash_equals((string) $_SESSION['installer_token'], (string) ($_POST['token'] ?? ''))) {
            throw new RuntimeException('Invalid installer token. Reload the page and try again.');
        }
        $action = (string) ($_POST['installer_action'] ?? '');
        if ($action === 'reset_database_step') {
            unset($_SESSION['installer_setup']);
            $currentStep = 1;
        } elseif ($action === 'database_step') {
            foreach (installer_checks($root) as $check) {
                if (!$check[1]) {
                    throw new RuntimeException('Environment prerequisite failed: ' . $check[0] . ' (' . $check[2] . ').');
                }
            }
            $siteName = installer_post('site_name', $defaults['site_name']);
            $baseUrl = rtrim(installer_post('base_url', $defaults['base_url']), '/');
            $db = [
                'host' => installer_post('db_host', 'localhost'),
                'port' => installer_post('db_port', '3306'),
                'name' => installer_post('db_name'),
                'user' => installer_post('db_user'),
                'password' => (string) ($_POST['db_password'] ?? ''),
            ];
            if ($siteName === '' || $baseUrl === '') {
                throw new RuntimeException('Site name and base URL are required.');
            }
            if (!filter_var($baseUrl, FILTER_VALIDATE_URL)) {
                throw new RuntimeException('Base URL must be an absolute URL, for example https://ppl.example.com.');
            }
            if ($db['name'] === '' || $db['user'] === '') {
                throw new RuntimeException('Database name and database user are required.');
            }
            if ($db['port'] !== '' && (!ctype_digit($db['port']) || (int) $db['port'] < 1 || (int) $db['port'] > 65535)) {
                throw new RuntimeException('Database port must be between 1 and 65535.');
            }
            installer_connect($db)->query('SELECT 1');
            $_SESSION['installer_setup'] = ['site_name' => substr($siteName, 0, 120), 'base_url' => $baseUrl, 'database' => $db];
            $_SESSION['installer_token'] = installer_secret(16);
            $currentStep = 2;
        } elseif ($action === 'admin_step') {
            if (!isset($_SESSION['installer_setup']) || !is_array($_SESSION['installer_setup'])) {
                throw new RuntimeException('Verify the database setup in step one.');
            }
            $setup = $_SESSION['installer_setup'];
            $adminUser = installer_post('admin_username', $defaults['admin_username']);
            $adminPassword = (string) ($_POST['admin_password'] ?? '');
            $adminPasswordAgain = (string) ($_POST['admin_password_again'] ?? '');
            if ($adminUser === '' || strlen($adminUser) > 190) {
                throw new RuntimeException('Administrator username is required and must be at most 190 characters.');
            }
            if (mb_strlen($adminPassword, 'UTF-8') < 15) {
                throw new RuntimeException('Administrator password must contain at least 15 characters.');
            }
            if (!hash_equals($adminPassword, $adminPasswordAgain)) {
                throw new RuntimeException('Enter the same administrator password in both fields.');
            }
            if (!is_dir($root . '/data/source-documents') && !mkdir($root . '/data/source-documents', 0775, true)) {
                throw new RuntimeException('Creating data/source-documents failed.');
            }
            if (!is_writable($root . '/data/source-documents')) {
                throw new RuntimeException('PHP requires write access to data/source-documents.');
            }

            if (!is_dir($root . '/cache') && !mkdir($root . '/cache', 0775, true)) {
                throw new RuntimeException('Creating the cache directory failed.');
            }
            if (!is_writable($root . '/cache')) {
                throw new RuntimeException('PHP requires write access to cache/.');
            }
            $pdo = installer_connect($setup['database']);
            $ran = \PplStudy\Core\run_migrations($pdo);
            installer_create_admin($pdo, $adminUser, $adminPassword);
            installer_save_settings($pdo, (string) $setup['site_name']);
            $bankSummary = \PplStudy\Services\import_bundled_question_bank(true, $pdo);
            $config = [
                'database' => [
                    'host' => (string) $setup['database']['host'],
                    'port' => (int) ($setup['database']['port'] !== '' ? $setup['database']['port'] : 3306),
                    'name' => (string) $setup['database']['name'],
                    'user' => (string) $setup['database']['user'],
                    'password' => (string) $setup['database']['password'],
                    'charset' => 'utf8mb4',
                ],
                'base_url' => (string) $setup['base_url'],
                'session_name' => 'ppl_study_' . substr(installer_secret(8), 0, 12),
                'csrf_secret' => installer_secret(32),
                'setup_key' => installer_secret(24),
                'runtime_limits' => [],
            ];
            installer_write_config($configFile, $config);
            if (file_put_contents($lockFile, 'Installed at ' . gmdate('c') . PHP_EOL, LOCK_EX) === false) {
                throw new RuntimeException('Writing the installation lock in cache/ failed.');
            }
            $adminUrl = rtrim((string) $setup['base_url'], '/') . '/admin';
            $messages[] = 'Installation finished.';
            $messages[] = 'Applied migrations: ' . ($ran === [] ? 'none' : implode(', ', $ran));
            $messages[] = 'Imported ' . $bankSummary['questions'] . ' cards in ' . $bankSummary['subjects'] . ' subjects.';
            unset($_SESSION['installer_setup']);
            $_SESSION['installer_token'] = installer_secret(16);
            $currentStep = 3;
        }
    }
} catch (Throwable $exception) {
    $error = $exception->getMessage();
    $currentStep = isset($_SESSION['installer_setup']) ? 2 : 1;
}

