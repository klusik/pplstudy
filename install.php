/** HTML-escape one installer value. */
function installer_e(?string $value): string
{
    return htmlspecialchars((string) $value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

/** Read one trimmed POST field. */
function installer_post(string $name, string $default = ''): string
{
    return trim((string) ($_POST[$name] ?? $default));
}

/** Return a cryptographically strong deployment secret. */
function installer_secret(int $bytes = 32): string
{
    return bin2hex(random_bytes($bytes));
}

/** Detect the current absolute base URL from the installer request. */
function installer_default_base_url(): string
{
    $forwardedProto = strtolower(trim(explode(',', (string) ($_SERVER['HTTP_X_FORWARDED_PROTO'] ?? ''))[0]));
    $https = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off')
        || (string) ($_SERVER['SERVER_PORT'] ?? '') === '443'
        || $forwardedProto === 'https'
        || strtolower((string) ($_SERVER['HTTP_X_FORWARDED_SSL'] ?? '')) === 'on';
    $scheme = $https ? 'https' : 'http';
    $host = (string) ($_SERVER['HTTP_HOST'] ?? 'localhost');
    $script = str_replace('\\', '/', (string) ($_SERVER['SCRIPT_NAME'] ?? '/install.php'));
    $dir = rtrim(str_replace('/install.php', '', $script), '/');
    return rtrim($scheme . '://' . $host . $dir, '/');
}

/** Build the installer PDO DSN. */
function installer_dsn(array $db): string
{
    return 'mysql:host=' . ($db['host'] !== '' ? $db['host'] : 'localhost')
        . ';port=' . (int) ($db['port'] !== '' ? $db['port'] : 3306)
        . ';dbname=' . $db['name']
        . ';charset=utf8mb4';
}

/** Connect to the database selected in step one. */
function installer_connect(array $db): PDO
{
    return new PDO(installer_dsn($db), $db['user'], $db['password'], [
        PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
        PDO::ATTR_EMULATE_PREPARES => false,
    ]);
}

/** Write config.php atomically enough for normal shared-hosting deployment. */
function installer_write_config(string $path, array $config): void
{
    $php = "<?php\n\n/** Generated by PPL Study installer. */\n\ndeclare(strict_types=1);\n\nreturn " . var_export($config, true) . ";\n";
    if (file_put_contents($path, $php, LOCK_EX) === false) {
        throw new RuntimeException('Writing config.php failed. Check directory permissions.');
    }
    @chmod($path, 0640);
}

/** Create or replace the initial administrator. */
function installer_create_admin(PDO $pdo, string $username, string $password): void
{
    $now = gmdate('Y-m-d H:i:s');
    $stmt = $pdo->prepare("INSERT INTO users (username, display_name, password_hash, role, must_change_password, temporary_password_consumed_at, active, created_by_user_id, last_login_at, password_changed_at, created_at, updated_at)
        VALUES (?, ?, ?, 'admin', 0, NULL, 1, NULL, NULL, ?, ?, ?)
        ON DUPLICATE KEY UPDATE display_name = VALUES(display_name), password_hash = VALUES(password_hash), role = 'admin', must_change_password = 0, temporary_password_consumed_at = NULL, active = 1, password_changed_at = VALUES(password_changed_at), updated_at = VALUES(updated_at)");
    $stmt->execute([$username, $username, password_hash($password, PASSWORD_DEFAULT), $now, $now, $now]);
}

/** Save initial public site settings directly through the installer database connection. */
function installer_save_settings(PDO $pdo, string $siteName): void
{
    $values = [
        'site_name' => $siteName,
        'site_subtitle' => 'Dynamický studijní systém pro teoretickou zkoušku PPL(A)',
        'home_intro' => 'Studuj aktuální banku otázek z devíti předmětů, procvičuj náhodné otázky a spusť paper drill se stejným počtem otázek a časem jako v přehledu zkoušky.',
        'source_disclaimer' => 'První předmět používá přesné znění a možnosti z dodaného oficiálního PDF ÚCL; další předměty se převádějí stejným postupem. Pro skutečný provoz mají přednost aktuální předpisy, AIP, NOTAM, AFM/POH a instrukce ATS.',
        'default_drill_count' => '20',
    ];
    $stmt = $pdo->prepare('INSERT INTO app_settings (setting_key, setting_value, updated_at) VALUES (?, ?, ?) ON DUPLICATE KEY UPDATE setting_value = VALUES(setting_value), updated_at = VALUES(updated_at)');
    foreach ($values as $key => $value) {
        $stmt->execute([$key, $value, gmdate('Y-m-d H:i:s')]);
    }
}

/** Return environment checks shown before step one. */
function installer_checks(string $root): array
{
    return [
        ['PHP 8.1+', version_compare(PHP_VERSION, '8.1.0', '>='), PHP_VERSION],
        ['PDO MySQL', extension_loaded('pdo_mysql'), extension_loaded('pdo_mysql') ? 'loaded' : 'missing'],
        ['JSON', extension_loaded('json'), extension_loaded('json') ? 'loaded' : 'missing'],
        ['mbstring', extension_loaded('mbstring'), extension_loaded('mbstring') ? 'loaded' : 'missing'],
        ['Project root writable', is_writable($root), is_writable($root) ? 'writable' : 'write access required'],
        ['cache/ writable or creatable', is_dir($root . '/cache') ? is_writable($root . '/cache') : is_writable($root), is_dir($root . '/cache') ? $root . '/cache' : 'will be created'],
        ['data/source-documents writable or creatable', is_dir($root . '/data/source-documents') ? is_writable($root . '/data/source-documents') : is_writable($root . '/data'), is_dir($root . '/data/source-documents') ? $root . '/data/source-documents' : 'will be created'],
        ['Bundled question bank', is_file($root . '/data/question-bank.json'), is_file($root . '/data/question-bank.json') ? 'present' : 'missing'],
    ];
}

